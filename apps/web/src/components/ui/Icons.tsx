import type { SVGProps } from 'react';

/**
 * Icon set.
 *
 * Hand-rolled rather than pulled from a library: the app needs about thirty
 * glyphs, and a dependency that ships a thousand costs more in bundle size and
 * version churn than these few lines. All share one 24px grid and inherit
 * `currentColor`, so an icon always matches the text it sits beside.
 */

interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'size'> {
  size?: number;
}

function icon(path: React.ReactNode, displayName: string) {
  const Component = ({ size = 16, ...props }: IconProps) => (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {path}
    </svg>
  );
  Component.displayName = displayName;
  return Component;
}

